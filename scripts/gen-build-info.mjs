// Writes server/build-info.ts at build time so the running server can report
// EXACTLY which commit produced the bundle it is executing.
//
// Why this exists: production serves a COMMITTED dist/ (Render's build does not
// regenerate it), and /api/health returned only a static "VEDD AI is running".
// So there was no way to tell from outside whether a deploy had actually landed.
// On 2026-09-19 that cost hours: the FX engine looked stopped, and we could not
// distinguish "the fix is deployed and something else is wrong" from "the build
// predates the fix". Baking the commit into the bundle answers that in one
// request — and because it is baked at BUILD time rather than read from the
// environment, it reports the commit whose dist is actually running, which is
// the thing that matters when dist can be stale relative to the repo.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const sh = (cmd, fallback) => {
  try { return execSync(cmd, { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); }
  catch { return fallback; }
};

const commit = sh('git rev-parse --short HEAD', 'unknown');
const branch = sh('git rev-parse --abbrev-ref HEAD', 'unknown');
// "-dirty" means the bundle was built from uncommitted edits, so the commit
// alone does not describe it.
const dirty = sh('git status --porcelain', '') ? '-dirty' : '';
const builtAt = new Date().toISOString();

writeFileSync(
  join(root, 'server', 'build-info.ts'),
  `// AUTO-GENERATED by scripts/gen-build-info.mjs at build time. Do not edit.\n` +
  `export const BUILD_COMMIT = ${JSON.stringify(commit + dirty)};\n` +
  `export const BUILD_BRANCH = ${JSON.stringify(branch)};\n` +
  `export const BUILT_AT = ${JSON.stringify(builtAt)};\n`,
  'utf8'
);

console.log(`[build-info] commit=${commit}${dirty} branch=${branch} builtAt=${builtAt}`);
