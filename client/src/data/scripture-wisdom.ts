export function getDailyScripture(): ScriptureWisdom {
  const today = new Date();
  // Use a hash of the full date string so it changes every day and doesn't repeat for 50 days
  const dateKey = `${today.getFullYear()}-${today.getMonth()}-${today.getDate()}`;
  let hash = 0;
  for (let i = 0; i < dateKey.length; i++) {
    hash = (hash * 31 + dateKey.charCodeAt(i)) >>> 0;
  }
  const index = hash % scriptureWisdom.length;
  return scriptureWisdom[index];
}

export function getRandomScripture(excludeIndex?: number): ScriptureWisdom {
  let index = Math.floor(Math.random() * scriptureWisdom.length);
  // Avoid showing the same one if excludeIndex is provided
  if (excludeIndex !== undefined && scriptureWisdom.length > 1) {
    while (index === excludeIndex) {
      index = Math.floor(Math.random() * scriptureWisdom.length);
    }
  }
  return scriptureWisdom[index];
}

export function getScriptureIndex(scripture: ScriptureWisdom): number {
  return scriptureWisdom.findIndex(s => s.reference === scripture.reference);
}
